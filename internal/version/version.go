// All 返回当前版本与全部历史版本号。
func All() []string {
	out := make([]string, 0, len(History)+1)
	out = append(out, Version)
	out = append(out, History...)
	return out
}

// IsKnown 报告 v 是当前版本或已登记的历史版本。
func IsKnown(v string) bool {
	for _, k := range All() {
		if k == v {
			return true
		}
	}
	return false
}
