// Package nginx 把领域模型渲染为 Nginx 配置。
// 渲染分两层：http 级（限速 zone、map、log_format）和 site 级（server 块）。
// http 级指令不能出现在 server 块内，因此单独生成并由主配置 include。
package nginx

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/zhiwei/panel/internal/model"
)

// LogFormatName 面板在 http 级定义的访问日志格式名。
// 站点配置统一引用它，避免每个站点重复定义 log_format（重复定义会直接报错）。
const LogFormatName = "zhiweipanel_access"

// RenderOptions 渲染上下文。
type RenderOptions struct {
	// SiteID 用于生成唯一的 zone/map 名称。
	SiteID string
	// PathRewrites 伪静态配置文件内容。
	PathRewrites string
	// DefaultPHPSocket PHP-FPM 默认 socket。
	DefaultPHPSocket string
	// PublicPort 全局对外端口（v0.2.1）。
	// 0 = 用 site 自身的 ListenPorts；非 0 = 覆盖（适合整站搬迁到非标端口）。
	// SSL 站点时 443 仍会追加（因为 443 是 TLS 公认端口）。
	PublicPort int
	// DisableIPv6 关闭 v6 监听（部分老机器没 IPv6，nginx 启动会报 emerg）。
	DisableIPv6 bool
	// OverQuotaQuotaHit 是否已超额（用于 enforce_quota）。
	QuotaExceeded bool
	// AccessFile 是本站点的 htpasswd 口令文件**完整路径**。
	//
	// 面板把每个站点的口令文件写在数据目录下的 htpasswd/ 里（文件名 = 站点 ID），
	// nginx 用 auth_basic_user_file 引用它。
	// 路径必须由调用方给出而不是在这里拼：nginx 只认正斜杠路径，
	// 而 filepath.Join 在 Windows 上会产出反斜杠。
	// 留空 = 不渲染 auth_basic（此时即使站点配了访问认证也不生效）。
	AccessFile string
}

// RenderResult 渲染产物。
type RenderResult struct {
	// SiteConf 单站点 server 块内容。
	SiteConf string
	// HTTPConf 需要写入 http 级上下文的指令。
	HTTPConf string
}

// Render 把站点渲染成 Nginx 配置。
//
// 渲染前有三道防线，顺序不能换：
//
//  1. 域名校验：没有合法域名就没有 server_name，站点无法对外服务，
//     属于站点级致命错误，直接返回。
//  2. 路径校验：路径没有"安全降级"语义（替换成别的目录 = 静默 404），
//     同样按站点级致命错误处理。
//  3. 净化：其余字段（IP 名单、UA 屏蔽词、反代目标、重定向……）非法时
//     丢弃或回落，**不**让渲染失败。
//
// 第 3 步是关键：如果脏数据能让 Render 报错，那么
//
//	Render 失败 → ApplyAllConfig 整体中止 → **所有站点**的配置都停在旧版本
//
// 一个站点的历史脏字段会连带把整台面板的其它站点一起卡住。
func Render(s *model.Site, opt RenderOptions) (RenderResult, error) {
	if err := s.Domains.Validate(); err != nil {
		return RenderResult{}, err
	}
	if err := model.ValidateSitePaths(s); err != nil {
		return RenderResult{}, err
	}
	// 净化：非法值丢弃或回落，保证单个脏字段不会拖垮整份配置。
	safe := model.SanitizeSite(s)
	r := &renderer{site: safe, opt: opt}
	r.buildHTTP()
	r.buildServer()
	return RenderResult{SiteConf: r.buf.String(), HTTPConf: r.httpBuf.String()}, nil
}

type renderer struct {
	site    *model.Site
	opt     RenderOptions
	buf     strings.Builder
	httpBuf strings.Builder
	// forceRedirect 由 buildSSLRedirect 置位，buildLocation 在 location / 里消费。
	// 不能放在 server 级：server 级的 if(...) return 在 location 匹配之前执行，
	// 会把 ACME 的 HTTP-01 挑战也 301 掉，导致证书续期失败。
	forceRedirect bool
	// locations 已占用的 location 匹配串，用于去重防 duplicate location。
	locations map[string]bool
	// rootReplacedByProxy 主 location "/" 是否被某条 proxy 规则接管。
	// 接管后 buildLocation 跳过主 location / 的输出（避免 duplicate location），
	// 且不再输出 try_files / expires / gzip / 强制 HTTPS 跳转等，
	// 因为整站反代不应再尝试本地静态服务。
	rootReplacedByProxy bool
}

func (r *renderer) w(format string, args ...any) {
	fmt.Fprintf(&r.buf, format, args...)
	r.buf.WriteString("\n")
}

func (r *renderer) hw(format string, args ...any) {
	fmt.Fprintf(&r.httpBuf, format, args...)
	r.httpBuf.WriteString("\n")
}

// buildHTTP 生成 http 级指令：限速 zone、上传大小、resolver。
func (r *renderer) buildHTTP() {
	s := r.site

	// 每 IP 限速 zone，zone 名必须全站唯一。
	if s.Traffic.RateLimitPerIP > 0 {
		r.hw("limit_req_zone $binary_remote_addr zone=%s_rate:10m rate=%dr/s;", s.ID, s.Traffic.RateLimitPerIP)
		r.hw("limit_conn_zone $binary_remote_addr zone=%s_conn:10m;", s.ID)
	}

	// 子目录绑定不需要在 http 级生成 map。
	// 早期这里输出 map $uri $<id>_subdir_root，但有两个问题：
	//   1. 全仓没有任何地方消费 $<id>_subdir_root，是死代码；
	//   2. nginx 的 map key 是字面量，不插值变量，写成 "/blog/$uri"
	//      永远匹配不上。
	// 子目录实际由 buildSubDirBindings 的 alias location 完成，
	// 删掉这段 map 不影响功能，只是少一份误导人的配置。
}

// buildServer 生成 server 块。
func (r *renderer) buildServer() {
	s := r.site
	r.w("# ============================================")
	r.w("# Site: %s  (id=%s)", s.Name, s.ID)
	r.w("# Generated by ZhiweiPanel — 请通过面板修改，勿手工编辑")
	r.w("# ============================================")
	r.w("")

	// ---------- HTTP 监听 ----------
	// 只有同时具备 ssl 监听与证书时才输出 ssl，否则 nginx 会因缺证书拒绝启动。
	sslReady := r.sslReady()
	r.w("server {")
	// 决定对外端口：全局 -public-port 覆盖；否则用 site.ListenPorts；
	// SSL 站点时 443 强制加入（443 是 TLS 公认端口，ACME HTTP-01 续签不依赖 443
	// 但浏览器 https 入口需要）。
	ports := r.effectiveListenPorts(sslReady)
	for _, p := range ports {
		if sslReady && p == 443 {
			r.w("    listen %d ssl;", p)
		} else {
			r.w("    listen %d;", p)
		}
		if !r.opt.DisableIPv6 {
			if sslReady && p == 443 {
				r.w("    listen [::]:%d ssl;", p)
			} else {
				r.w("    listen [::]:%d;", p)
			}
		}
	}
	r.w("    server_name %s;", s.Domains.All())
	// root 必须写在 server 级。PHP location 用 $document_root$fastcgi_script_name
	// 拼 SCRIPT_FILENAME，而 $document_root 取的是"当前层级生效的 root"；
	// 若只在 location / 里写 root，PHP location 里就会回落到 nginx 默认根目录，
	// 表现为 .php 请求返回 404 "File not found."（而直连 FPM 是正常的，极具迷惑性）。
	if s.Root.Path != "" {
		r.w("    root %s;", ensureTrailingSlash(s.Root.Path))
	}
	r.w("")
	// 顺序有讲究：
	//   1. buildSSLRedirect 只是置位 forceRedirect 标志，必须最先跑，
	//      否则 buildLocation 读不到标志、HTTPS 跳转就丢了；
	//   2. buildLocation 接着占掉主 location "/"，
	//      之后 buildProxy / buildRedirects / buildSubDirBindings 里若也有人填 "/"，
	//      才会在 claimLocation 处被跳过而不是生成 duplicate location。
	r.buildSSLRedirect()
	// 必须在 buildLocation 之前扫描 proxy 规则：识别"整站反代"
	// 场景，让 buildLocation 跳过主 location / 让位给 proxy_pass。
	r.buildProxyScan()
	r.buildLocation()
	r.buildServerTokens()
	r.buildIndex()
	r.buildClientBody()
	r.buildRealIP()
	r.buildLogs()
	r.buildSecurity()
	r.buildDenyRules()
	r.buildRateLimit()
	r.buildHotlink()
	r.buildAccess()
	r.buildBasicAuth()
	r.buildProxy()
	r.buildTLS()
	r.buildACMEChallenge()
	r.buildCustom404()
	r.buildRewrites()
	r.buildSubDirBindings()
	r.buildRedirects()
	r.buildRawConf()
	r.w("}")
	r.w("")
}

// claimLocation 登记一个 location 前缀，返回是否可占用。
//
// 必须做去重：nginx 不允许同一 server 块内出现重复的 location 匹配串，
// 一旦重复 nginx -t 直接报 "duplicate location"，
// 导致 ApplyAllConfig 整体回滚——**所有站点**的本次变更都无法生效。
//
// 最常见的冲突是用户把重定向来源或反代路径填成 "/"
// （意图是"整站跳转/整站反代"），与主 location / 撞车。
// 此时跳过后者（主 location 一定赢），并在配置里留注释说明。
func (r *renderer) claimLocation(spec string) bool {
	if r.locations == nil {
		r.locations = map[string]bool{}
	}
	if r.locations[spec] {
		return false
	}
	r.locations[spec] = true
	return true
}

// listenPort 站点监听端口。SSL 站点默认 443，否则 80。
func (r *renderer) buildServerTokens() {
	if r.site.Security.ServerTokensOff {
		r.w("    server_tokens off;")
	}
}

// buildIndex 默认文档。
func (r *renderer) buildIndex() {
	files := r.site.Index.Files
	if len(files) == 0 {
		files = []string{"index.php", "index.html", "index.htm"}
	}
	r.w("    index %s;", strings.Join(files, " "))
}

// buildClientBody 上传限制。
func (r *renderer) buildClientBody() {
	if v := r.site.Extra.ClientMaxBodySize; v != "" {
		r.w("    client_max_body_size %s;", v)
	}
}

// buildRealIP 真实 IP（CDN/反代场景）。
//
// 绝不能写 set_real_ip_from 0.0.0.0/0：那等于信任全网，
// 攻击者直连源站伪造一个 X-Forwarded-For 头就能同时绕过
// IP 白名单（allow/deny）与按 IP 限速（limit_req_zone 用
// $binary_remote_addr），并污染访问日志里的 IP。
// 可信代理必须由用户显式给出 CIDR 列表；没有配置就不开启。
func (r *renderer) buildRealIP() {
	resolver := r.site.Extra.DNSResolver
	trusted := r.site.Extra.TrustedProxies
	if len(trusted) == 0 {
		return
	}
	for _, cidr := range trusted {
		cidr = strings.TrimSpace(cidr)
		if cidr == "" || strings.ContainsAny(cidr, ";{}\"'`\\\n\r") {
			continue
		}
		r.w("    set_real_ip_from %s;", cidr)
	}
	r.w("    real_ip_header X-Forwarded-For;")
	r.w("    real_ip_recursive on;")
	if resolver != "" {
		// resolver 让 proxy_pass 使用域名变量时可以解析
		r.w("    resolver %s valid=30s;", sanitizeResolver(resolver))
	}
}

// sanitizeResolver 校验 resolver 值，只允许 IP[:端口] 空白分隔的形式。
func sanitizeResolver(v string) string {
	fields := strings.Fields(v)
	out := make([]string, 0, len(fields))
	for _, f := range fields {
		f = strings.TrimSuffix(strings.TrimSpace(f), ";")
		if f == "" || strings.ContainsAny(f, ";{}\"'`\\\n\r") {
			continue
		}
		out = append(out, f)
	}
	return strings.Join(out, " ")
}

// buildLogs 日志配置。
func (r *renderer) buildLogs() {
	l := r.site.Logs
	if l.DisableLog {
		r.w("    access_log off;")
		r.w("    error_log /dev/null crit;")
		return
	}
	if l.AccessLog {
		// access_log 路径后跟的是 log_format 名称，不是变量。
		// 写 $host 这类变量会被 nginx 当成格式名查找并报
		// "unknown log format"，导致整个配置加载失败。
		r.w("    # 面板访问日志（格式由 http 级 log_format zhiweipanel_access 定义）")
		r.w("    access_log %s/logs/access.log %s;", r.site.Root.Path, logFormatName(l.CustomFormat))
	} else {
		r.w("    access_log off;")
	}
	if l.ErrorLog {
		r.w("    error_log %s/logs/error.log warn;", r.site.Root.Path)
	} else {
		r.w("    error_log off;")
	}
}

// logFormatName 返回要写在 access_log 末尾的 log_format 名称。
//
// nginx 的 access_log 语法是：access_log <path> <format>;
// 第二个参数必须是 http 级用 log_format 定义的名称，不能是 $ 变量。
// 用户没填就用面板定义的 zhiweipanel_access。
func logFormatName(custom string) string {
	custom = strings.TrimSpace(custom)
	if custom == "" || strings.HasPrefix(custom, "$") {
		return LogFormatName
	}
	// 只允许安全的标识符，避免把任意内容注入配置
	for _, r := range custom {
		isAlnum := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') ||
			(r >= '0' && r <= '9') || r == '_'
		if !isAlnum {
			return LogFormatName
		}
	}
	return custom
}

// securityHeaders 输出安全响应头，供 server 级与需要自定义 add_header 的
// location 共用（nginx 下本级有 add_header 就不继承上级，故需显式重复）。
// HSTS 只在 TLS 就绪时输出：明文响应带上 HSTS 头会被浏览器拒绝生效。
func (r *renderer) securityHeaders(indent string) {
	sec := r.site.Security
	if sec.PreventIframe {
		r.w("%sadd_header X-Frame-Options \"SAMEORIGIN\" always;", indent)
	}
	if sec.ServerTokensOff {
		r.w("%sadd_header X-Powered-By \"\" always;", indent)
	}
	if r.sslReady() && r.site.SSL.HSTS {
		maxAge := r.site.SSL.HSTSMaxAge
		if maxAge <= 0 {
			maxAge = 31536000
		}
		r.w("%sadd_header Strict-Transport-Security \"max-age=%d\" always;", indent, maxAge)
	}
}

func (r *renderer) buildSecurity() {
	sec := r.site.Security

	// 安全响应头。
	r.securityHeaders("    ")

	// WAF：危险函数注入拦截。
	// $request_uri 是未经解码的原始 URI，攻击方常把 < ' 空格 编码成
	// %3C %27 %20，只匹配字面量会整类漏掉（实测：?q=%3Cscript%3E 直接放过）。
	// 因此模式里的特殊字符要扩展出编码变体。
	//
	// 两个 nginx 特定的坑，改动前务必先跑 TestWAFPatternSurvivesNginxUnescape：
	//  1. 结果写进 nginx 双引号字符串，nginx 会把 \\ 反转义成 \。
	//     所以正则里想表达"字面反斜杠"必须写四个，写两个会让尾随 \
	//     把分组右括号转义掉，报 pcre_compile() failed: missing )。
	//  2. 因此这里刻意不匹配 ..\\ （Windows 风格穿越）——Linux 上无意义，
	//     而它是上述转义问题最主要的来源。Unix 穿越由 \.\./ 覆盖。
	if sec.BlockSQLi || sec.BlockXSS || sec.BlockTraversal {
		r.w("    if ($request_uri ~* \"(?i)(%s)\") {",
			wafPattern(`union\s+select|insert\s+into|drop\s+table|delete\s+from|<script|javascript:|onerror\s*=|onload\s*=|\.\./`))
		r.w("        return 403;")
		r.w("    }")
	}

	// 日志目录默认拒绝外网访问。
	// access_log 就放在 <root>/logs/ 下，不拦的话请求
	// http://站点/logs/access.log 就能把全站 IP/UA/URL 下载走。
	r.w("    location ^~ /logs/ { deny all; }")
}

// wafPattern 把模式中的特殊字符扩展出 URL 编码变体。
// 正则转义序列（\s \d \. 等）原样保留，否则会被拆坏。
// 注意顺序：必须先做字符展开，再把 \s+ 放宽——反过来会让刚插入的
// 括号被二次展开成 (?:\(|%28)，正则直接废掉。
func wafPattern(p string) string {
	// 只扩展"在正则里不需要反斜杠"的字符；反斜杠本身不扩展，
	// 因为它会把 nginx 双引号反转义的坑引进来。
	enc := map[byte]string{
		' ': "%20", '<': "%3C", '>': "%3E", '\'': "%27", '"': "%22",
		'/': "%2F", '(': "%28", ')': "%29", '=': "%3D",
	}
	var sb strings.Builder
	for i := 0; i < len(p); i++ {
		c := p[i]
		if c == '\\' && i+1 < len(p) {
			// 转义序列整体拷贝
			sb.WriteByte(c)
			sb.WriteByte(p[i+1])
			i++
			continue
		}
		if e, ok := enc[c]; ok {
			sb.WriteString("(?:" + string(c) + "|" + e + ")")
			continue
		}
		sb.WriteByte(c)
	}
	// 编码后的空格对 \s 不成立，放宽为 (空格|%20|+)+
	return strings.ReplaceAll(sb.String(), `\s+`, `(?:\s|%20|\+)+`)
}

func (r *renderer) buildDenyRules() {
	sec := r.site.Security

	// 禁止访问的敏感路径。
	// 用精确前缀匹配而不是 normalizePathPrefix：后者会强制补尾斜杠，
	// 于是 /secret.html 变成 ^/secret\.html/，请求 /secret.html 反而匹配不上。
	for _, p := range sec.DenyPaths {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		spec := quotePathRE(p)
		if !r.claimLocation(spec) {
			continue // 重复的黑名单路径，跳过即可
		}
		r.w("    location ~* %s { deny all; }", spec)
	}

	// 禁止访问的扩展名。
	if len(sec.DenyExtensions) > 0 {
		exts := make([]string, 0, len(sec.DenyExtensions))
		for _, e := range sec.DenyExtensions {
			e = strings.TrimSpace(strings.TrimPrefix(e, "."))
			if e != "" {
				exts = append(exts, regexp.QuoteMeta(e))
			}
		}
		if len(exts) > 0 {
			r.w("    location ~* \\.(%s)$ { deny all; }", strings.Join(exts, "|"))
		}
	}

	// UA 黑名单。
	if sec.BlockUA && len(sec.BlockUAKeywords) > 0 {
		kws := make([]string, 0, len(sec.BlockUAKeywords))
		for _, k := range sec.BlockUAKeywords {
			if k = strings.TrimSpace(k); k != "" {
				kws = append(kws, regexp.QuoteMeta(k))
			}
		}
		if len(kws) > 0 {
			r.w("    if ($http_user_agent ~* \"(?i)(%s)\") { return 403; }", strings.Join(kws, "|"))
		}
	}
}

func (r *renderer) buildRateLimit() {
	t := r.site.Traffic

	if t.RateLimitPerIP > 0 {
		r.w("    limit_req zone=%s_rate burst=%d nodelay;", r.site.ID, burstOf(t.RateLimitPerIP))
		r.w("    limit_conn %s_conn 100;", r.site.ID)
		r.w("    limit_req_status 429;")
	}

	// 单连接限速。
	if t.BandwidthLimit != "" {
		r.w("    limit_rate %s;", t.BandwidthLimit)
		r.w("    limit_rate_after 1m;")
	}
}

// burstOf 按速率计算合理的 burst 值。
func burstOf(rate int) int {
	b := rate * 2
	if b < 10 {
		b = 10
	}
	if b > 200 {
		b = 200
	}
	return b
}

func (r *renderer) buildHotlink() {
	h := r.site.Hotlink
	if !h.Enabled || len(h.FileExtensions) == 0 {
		return
	}
	exts := make([]string, 0, len(h.FileExtensions))
	for _, e := range h.FileExtensions {
		e = strings.TrimSpace(strings.TrimPrefix(e, "."))
		if e != "" {
			exts = append(exts, regexp.QuoteMeta(e))
		}
	}
	if len(exts) == 0 {
		return
	}
	refs := []string{"none", "blocked"}
	refs = append(refs, h.AllowedDomains...)

	code := h.ReturnCode
	if code == 0 {
		code = 403
	}
	r.w("    location ~* \\.(%s)$ {", strings.Join(exts, "|"))
	r.w("        valid_referers %s;", strings.Join(refs, " "))
	r.w("        if ($invalid_referer) {")
	r.w("            return %d;", code)
	r.w("        }")
	r.w("        try_files $uri =404;")
	r.w("    }")
}

func (r *renderer) buildAccess() {
	a := r.site.Access
	if !a.Enabled {
		return
	}
	// 白名单优先：有 allow 时只放行白名单。
	if len(a.Allow) > 0 {
		r.w("    allow %s;", strings.Join(a.Allow, "; "))
		r.w("    deny all;")
	}
	for _, d := range a.Deny {
		r.w("    deny %s;", d)
	}
	// HTTP 方法限制。
	if len(a.AllowMethods) > 0 {
		r.w("    if ($request_method !~* \"^(%s)$\") { return 405; }",
			strings.Join(a.AllowMethods, "|"))
	}
}

// buildBasicAuth 输出 HTTP Basic Auth 指令（站点级访问认证）。
//
// 早期版本的模型里有 Access.AuthEnabled/AuthUser/AuthPass 三个字段，
// 界面上也画了"访问认证"这一栏，但**全仓没有任何一处渲染它们**——
// 用户配完毫无反应，典型的"配置项存在但功能缺失"。
//
// 三个必须同时满足才输出：
//  1. 站点开启了访问认证；
//  2. 面板给过口令（AuthHash 非空——明文口令已被换成 apr1 哈希）；
//  3. 渲染上下文里给了口令文件目录。
//
// 少任何一条都不输出 auth_basic：nginx 在**解析配置时**就会打开
// auth_basic_user_file 指向的文件，文件不存在时 nginx -t 直接报
// "open() failed"，而一次 nginx -t 失败会让 ApplyAllConfig 整体回滚，
// **所有站点**的配置都停不下来——为了一个站点的认证把整台面板拖下水，
// 代价完全不成比例。
func (r *renderer) buildBasicAuth() {
	a := r.site.Access
	if !a.AuthEnabled || a.AuthUser == "" || a.AuthHash == "" {
		return
	}
	if r.opt.AccessFile == "" {
		return
	}
	path := r.opt.AccessFile
	// 路径会原样写进 nginx 配置：带空格/引号/分号会改变配置结构，
	// 这里宁可不输出也不冒险（面板的数据目录带空格属于部署不规范）。
	if !model.NginxSafeFSPath(path) {
		return
	}
	realm := r.site.Domains.Primary()
	if realm == "" {
		realm = "Restricted"
	}
	r.w("    # 站点访问认证（HTTP Basic Auth）")
	r.w("    auth_basic \"%s\";", nginxQuoteString(realm))
	r.w("    auth_basic_user_file \"%s\";", path)
}

// nginxQuoteString 给 nginx 的双引号字符串做转义。
//
// nginx 配置里的字符串只认 \" 与 \\ 两个转义序列；
// 其余控制字符（换行等）会让配置解析直接失败。
func nginxQuoteString(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\"", "\\\"")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return s
}

// buildProxyScan 预扫描：检查是否有 path="/" 的 enabled 规则，若有则
// 标记 rootReplacedByProxy，让 buildLocation 跳过主 location 的 try_files。
//
// 必须在 buildLocation 之前跑（因为 buildLocation 一旦输出主 location /，
// 后续 buildProxy 会被 claimLocation 拒绝、走"跳过重复"分支，整站反代
// 就静默失效）。但 buildProxy 主体仍保持在 buildLocation 之后原位，
// 避免改动其它 location（deny/logs/.well-known）的输出顺序。
func (r *renderer) buildProxyScan() {
	p := r.site.Proxy
	if !p.Enabled {
		return
	}
	for _, rule := range p.Rules {
		if !rule.Enabled || rule.Target == "" {
			continue
		}
		prefix := normalizeProxyPrefix(rule.Path)
		if prefix == "/" {
			r.rootReplacedByProxy = true
			return // 标记位是 bool，找到一条就够
		}
	}
}

// buildProxy 反向代理。
func (r *renderer) buildProxy() {
	p := r.site.Proxy
	if !p.Enabled {
		return
	}
	for _, rule := range p.Rules {
		if !rule.Enabled || rule.Path == "" || rule.Target == "" {
			continue
		}
		timeout := rule.Timeout
		if timeout == 0 {
			timeout = 60
		}
		// 保留用户填写的原始路径：填 /api 走完整路径匹配，填 /api/ 才剥离前缀。
		// 这里不能强制补尾斜杠，否则用户填的 /ws 会被悄悄变成 /ws/。
		prefix := normalizeProxyPrefix(rule.Path)

		// 用 ^~ 前缀匹配：nginx 的正则 location 优先于普通前缀 location，
		// 不加强修饰符时，反代 /api/ 下的 .php 会被 location ~ \.php$
		// 抢走到 FPM， deny_paths 的正则也会把反代路径整个 403。
		//
		// 同时去重：path 填 "/" 时与主 location / 撞车，
		// nginx -t 会报 duplicate location 导致整份配置回滚。
		if !r.claimLocation(prefix) {
			r.w("    # 跳过重复的反代路径 %s（与其它 location 冲突，nginx 不允许重复）", prefix)
			continue
		}
		r.w("    location ^~ %s {", prefix)
		// 整站反代（path="/"）时 buildLocation 整体跳过，force_https 的
		// HTTP→HTTPS 跳转必须在这里补写：否则反代站点的 http:// 直接服务、
		// 不跳转，而面板上 force_https 开关仍显示"已开启"——典型的
		// "看起来配好了、实际没生效"静默故障。
		//
		// 为什么必须写在 location 内而不能放 server 级：server 级的
		// if(...) return 先于 location 匹配执行，会把 ACME 挑战目录一起
		// 301 掉，证书续签随之失败（见 buildSSLRedirect 注释）。
		// 写在 ^~ / 内是安全的：ACME 的 location ^~ /.well-known/acme-
		// challenge/ 是更长前缀，优先命中，不受影响。
		if prefix == "/" && r.forceRedirect {
			r.w("        if ($scheme = http) {")
			r.w("            return 301 https://$host$request_uri;")
			r.w("        }")
		}
		if rule.WebSocket {
			r.w("        proxy_http_version 1.1;")
			r.w("        proxy_set_header Upgrade $http_upgrade;")
			r.w("        proxy_set_header Connection \"upgrade\";")
		}
		r.w("        proxy_set_header Host $host;")
		r.w("        proxy_set_header X-Real-IP $remote_addr;")
		r.w("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
		r.w("        proxy_set_header X-Forwarded-Proto $scheme;")
		if rule.SNI {
			r.w("        proxy_ssl_server_name on;")
			r.w("        proxy_ssl_name $host;")
		}
		r.w("        proxy_connect_timeout %ds;", timeout)
		r.w("        proxy_read_timeout %ds;", timeout)
		r.w("        proxy_send_timeout %ds;", timeout)
		r.w("        proxy_redirect off;")

		// /api 形式：保留完整路径；/api/ 形式：剥离前缀。
		// 归一化 target 尾斜杠：用户填的 target 是否带 "/" 是 UI 习惯差异，
		// 渲染时必须按 path 的尾斜杠决定，target 自身带不带 "/" 都不应影响。
		// 否则 path=/mag（无尾斜杠，期望保留完整 URI）+ target=http://x:port/（带尾斜杠）
		// 会渲染出 proxy_pass http://x:port/; 配 location ^~ /mag → 请求 /mag/ 时
		// nginx 把前缀 /mag 替换为 /，剩下的 "/" 还在前面 → 上游收到 "//" 触发 ERR_INVALID_URL。
		target := strings.TrimSuffix(rule.Target, "/")
		if strings.HasSuffix(rule.Path, "/") {
			r.w("        proxy_pass %s/;", target)
		} else {
			r.w("        proxy_pass %s;", target)
		}

		if rule.CacheEnable && rule.CacheTime > 0 {
			r.w("        proxy_cache_valid 200 %dm;", rule.CacheTime)
		}
		r.w("    }")
	}
}

// buildTLS 输出 SSL 证书与协议配置。
func (r *renderer) buildTLS() {
	if !r.sslReady() {
		return
	}
	s := r.site
	r.w("    ssl_certificate %s;", s.SSL.CertFile)
	r.w("    ssl_certificate_key %s;", s.SSL.KeyFile)

	protocols := s.SSL.Protocols
	if len(protocols) == 0 {
		protocols = []string{"TLSv1.2", "TLSv1.3"}
	}
	r.w("    ssl_protocols %s;", strings.Join(protocols, " "))
	r.w("    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305;")
	r.w("    ssl_prefer_server_ciphers on;")
	r.w("    ssl_session_cache shared:SSL:10m;")
	r.w("    ssl_session_timeout 10m;")
	if s.SSL.OCSP {
		r.w("    ssl_stapling on;")
		r.w("    ssl_stapling_verify on;")
	}
	// HSTS 头由 securityHeaders() 统一输出（静态缓存 location 也要重复一遍），
	// 这里不再单独写，避免两处各写一半导致行为不一致。
	// 注意不要默认加 includeSubDomains：它会影响该域名下所有子域，
	// 用户没明确要求时不该替他决定。
}

// buildSSLRedirect 标记是否需要把 HTTP 跳转到 HTTPS。
// 真正的跳转指令由 buildLocation 写进 location / 内——server 级的
// if(...) return 会在 location 匹配之前执行，连 ACME 挑战一起跳掉。
func (r *renderer) buildSSLRedirect() {
	s := r.site
	if !r.sslReady() {
		return
	}
	if s.SSL.ForceHTTPS {
		r.forceRedirect = true
	}
}

// buildACMEChallenge 放行 Let's Encrypt 的 HTTP-01 挑战目录。
// 必须用 ^~ 前缀匹配，且不能被 force_https 跳转拦截，否则证书续期会失败。
func (r *renderer) buildACMEChallenge() {
	root := ensureTrailingSlash(r.site.Root.Path)
	if root == "/" || root == "" {
		return
	}
	r.w("    # ACME HTTP-01 挑战目录：直连 80，不跳 HTTPS（否则续签失败）")
	r.w("    location ^~ /.well-known/acme-challenge/ {")
	r.w("        root %s;", root)
	r.w("        default_type text/plain;")
	// 必须显式关掉访问认证：server 级开了 auth_basic 之后，
	// 这个 location 会继承认证要求，Let's Encrypt 的验证请求拿不到
	// 挑战文件 → 续签失败 → 证书过期 → 站点 HTTPS 全面不可用。
	r.w("        auth_basic off;")
	r.w("        try_files $uri =404;")
	r.w("    }")
}

// buildCustom404 自定义 404 页面（v0.2.0 借鉴宝塔）。
//
// extra.custom_404 是相对站点根目录的路径，如 "404.html" 或 "errors/404.php"。
// 留空 = 不输出任何 error_page，nginx 默认 404 响应。
//
// 用 server 级 error_page 指令：它对所有未匹配 location 的 404 兜底，
// 但已经被精确匹配 location（如反代）覆盖的 404 不受影响——这正是想要的行为。
func (r *renderer) buildCustom404() {
	p := strings.TrimSpace(r.site.Extra.Custom404)
	if p == "" {
		return
	}
	// 不允许跳出站点根
	if strings.HasPrefix(p, "/") || strings.Contains(p, "..") {
		return
	}
	r.w("    # 自定义 404 页面")
	r.w(`    error_page 404 /%s;`, p)
}

// sslReady 判断站点是否具备可用的 SSL 配置。
// 缺少证书文件时开启 ssl 监听会让 nginx 直接启动失败，因此必须退化为 HTTP。
func (r *renderer) sslReady() bool {
	return r.site.SSL.Enabled && r.site.SSL.CertFile != "" && r.site.SSL.KeyFile != ""
}

// effectiveListenPorts 决定这个站点要 listen 哪些端口。
//
// 解析顺序（v0.2.1）：
//  1. 全局 -public-port 非 0 → 用它做对外端口（整站搬迁到非标端口的场景）
//  2. 否则用 site.ListenPorts，留空 = [80]
//  3. SSL 站点：自动追加 443（TLS 公认端口；80 上的纯 http 走强制跳转）
//  4. 去重（防用户填 80 时还同时填了 443）
//  5. 不引入 0 / 越界值
func (r *renderer) effectiveListenPorts(sslReady bool) []int {
	var ports []int
	if r.opt.PublicPort > 0 {
		// 全局覆盖：只听这一个端口（SSL 时加上 443）
		ports = []int{r.opt.PublicPort}
	} else if len(r.site.ListenPorts) > 0 {
		ports = append(ports, r.site.ListenPorts...)
	} else {
		ports = []int{80}
	}
	if sslReady {
		has443 := false
		for _, p := range ports {
			if p == 443 {
				has443 = true
				break
			}
		}
		if !has443 {
			ports = append(ports, 443)
		}
	}
	// 去重 + 越界过滤
	seen := make(map[int]struct{}, len(ports))
	out := make([]int, 0, len(ports))
	for _, p := range ports {
		if p < 1 || p > 65535 {
			continue
		}
		if _, dup := seen[p]; dup {
			continue
		}
		seen[p] = struct{}{}
		out = append(out, p)
	}
	return out
}

// looksLikePHPServerVersion 判断版本串能不能用来推导 PHP-FPM socket 路径。
//
// 形如 "8.2" / "7.4" 才可以；"default" 这类非版本号不行——
// 早期版本拿 "default" 去拼 /run/php/phpdefault-fpm.sock，
// 拼出来的是一个不存在的路径，PHP 请求直接 502。
func looksLikePHPServerVersion(v string) bool {
	if v == "" {
		return false
	}
	parts := strings.Split(v, ".")
	if len(parts) < 2 || len(parts) > 3 {
		return false
	}
	for _, p := range parts {
		if p == "" {
			return false
		}
		for _, r := range p {
			if r < '0' || r > '9' {
				return false
			}
		}
	}
	return true
}

// buildSubDirBindings 生成子目录绑定 location。
//
// 必须是 server 的直接子块：nginx 不允许 location 嵌套 location，
// 写在 location / 内部会导致 nginx -t 直接失败。
func (r *renderer) buildSubDirBindings() {
	s := r.site
	if !s.SubDir.Enabled {
		return
	}
	for _, rule := range s.SubDir.Rules {
		p := normalizePathPrefix(rule.Path)
		if p == "/" || rule.Root == "" {
			continue
		}
		// 跳过与主 location / 冲突的前缀，否则 nginx -t 直接报
		// duplicate location，导致本次全部站点配置回滚。
		if p == "/" {
			continue
		}
		if !r.claimLocation(p) {
			r.w("    # 跳过重复的子目录绑定 %s（nginx 不允许重复 location）", p)
			continue
		}
		// try_files 的最后一项只在 PHP 启用时输出：否则 /blog/ 会
		// 回退到 /blog/index.php 再进同一 location，形成内部重定向循环。
		fallback := ""
		if s.PHP.Enabled {
			fallback = " " + strings.TrimSuffix(p, "/") + "/index.php?$query_string"
		}
		r.w("    # 子目录绑定: %s -> %s", p, rule.Root)
		r.w("    location %s {", p)
		r.w("        alias %s;", ensureTrailingSlash(rule.Root))
		r.w("        index %s;", strings.Join(indexDefaults(s.Index), " "))
		r.w("        try_files $uri $uri/%s;", fallback)
		r.w("    }")
	}
	// PHP 子目录需要在 server 级单独放行
	if s.PHP.Enabled {
		for _, rule := range s.SubDir.Rules {
			p := normalizePathPrefix(rule.Path)
			if p == "/" || rule.Root == "" {
				continue
			}
			r.w("    location ~ ^%s.*\\.php$ {", regexp.QuoteMeta(p))
			r.w("        alias %s;", ensureTrailingSlash(rule.Root))
			r.phpFastCGI("        ", true)
			r.w("    }")
		}
	}
}

// buildLocation 生成主 location 与 PHP location。
func (r *renderer) buildLocation() {
	s := r.site

	root := ensureTrailingSlash(s.Root.Path)

	// 整站反代场景：某条 proxy rule 的 path 是 "/" 且 enabled，
	// 主 location 完全交给 proxy_pass。buildProxy 在 buildLocation
	// 之前已置位 rootReplacedByProxy 并 claimLocation("/")，这里直接返回。
	if r.rootReplacedByProxy {
		// PHP/伪静态等其它 location 仍可输出（虽然被主 location / 接管后
		// 通常用不到）。但 .php 与子目录绑定与主 location 顺序敏感，
		// 此处保守：仅当 php 关闭且无子目录绑定时才彻底跳过。
		// 当前策略：仍输出 .php location（与接管主 location 协同），
		// 但不再生成 location / 与 try_files 静态 fallback。
		return
	}

	// 主 location 一定存在，因此它优先占用 "/"。
	// 反代/重定向/子目录若也填 "/"，会在各自的 claimLocation 处被跳过。
	r.claimLocation("/")
	r.w("    location / {")

	// HTTP 跳 HTTPS 必须写在 location 内，不能写在 server 级：
	// server 级的 if(...) return 先于 location 匹配执行，会把
	// /.well-known/acme-challenge/ 一起 301 掉，证书就续不了了。
	if r.forceRedirect {
		r.w("        if ($scheme = http) {")
		r.w("            return 301 https://$host$request_uri;")
		r.w("        }")
	}

	if s.Extra.BrowserCache > 0 {
		// nginx 的 expires 指令不带单位后缀，写成 86400s 会直接语法报错。
		// expires 本身就会同时设置 Expires 和 Cache-Control，
		// 早期这里还额外 add_header Cache-Control，是重复的，
		// 而且它会顶掉 server 级继承来的 add_header（包括自定义配置里的）。
		r.w("        expires %d;", s.Extra.BrowserCache)
	}
	if s.Extra.Gzip {
		r.w("        gzip on;")
		r.w("        gzip_types %s;", gzipTypes(s.Extra))
		if s.Extra.GzipMinLength > 0 {
			r.w("        gzip_min_length %d;", s.Extra.GzipMinLength)
		}
		r.w("        gzip_vary on;")
	}
	if s.Traffic.BandwidthLimit != "" {
		// limit_rate 已在 server 级设置过，这里不再重复输出，
		// 避免同一层级出现两条同义指令造成排查困扰。
		_ = s.Traffic.BandwidthLimit
	}

	r.w("        root %s;", root)
	r.w("        try_files $uri $uri/ /index.php?$query_string;")
	r.w("    }")

	// 静态资源缓存：必须是 server 的直接子块。
	// nginx 不允许 location 嵌套，写在 location / 内部会导致 nginx -t 直接失败。
	if exts := staticExts(s.Extra.StaticCacheExt); len(exts) > 0 {
		r.w("    # 静态资源缓存")
		r.w("    location ~* \\.(%s)$ {", strings.Join(exts, "|"))
		// 相对路径 location 不继承外层 root，必须显式指定，否则静态文件 404
		r.w("        root %s;", root)
		r.w("        expires %d;", cacheMax(s.Extra.BrowserCache))
		r.w("        add_header Cache-Control \"public, immutable\";")
		// nginx 规则：本级一旦出现任一 add_header，就不再继承上级的全部
		// add_header。因此这里必须把 server 级的安全头重复输出一遍，
		// 否则同时开启缓存与安全选项时，静态资源的 X-Frame-Options/
		// X-Powered-By/HSTS 会静默丢失。
		r.securityHeaders("        ")
		r.w("        try_files $uri =404;")
		r.w("    }")
	}

	// PHP location。
	if s.PHP.Enabled {
		r.w("")
		r.w("    location ~ \\.php$ {")
		r.phpFastCGI("        ", false)
		r.w("    }")
	}

	// 重定向规则由 buildServer 在最外层统一调用（需在主 location 之后），
	// 这里不再重复调用，否则同一批 location 会输出两遍。

	// 超额拒绝。
	// 必须真正消费 $zw_quota_lock：早期只 set 不读，界面显示"已锁定"
	// 实际流量照常放行，enforce_quota 整个是空操作。
	if s.Traffic.EnforceQuota && r.opt.QuotaExceeded {
		r.w("    # 流量配额已超额：拒绝后续请求")
		r.w("    set $zw_quota_lock 1;")
		r.w("    if ($zw_quota_lock) {")
		r.w("        return 403;")
		r.w("    }")
	}
}

// phpFastCGI 输出 PHP-FPM 转发配置。
// subdir 为 true 时使用 alias，需要用 realpath_root 拼出真实脚本路径。
//
// v0.2.0: 增加 run_path 支持（Laravel/ThinkPHP 风格）。
// 当 site.Root.RunPath 非空时，SCRIPT_FILENAME 拼成
//
//	$document_root/<run_path>/$fastcgi_script_name
//
// nginx 在 SCRIPT_FILENAME 上**只**取最后一个值（不取合并），所以
// 整个 location 只输出这一条 fastcgi_param 指令。
func (r *renderer) phpFastCGI(indent string, subdir bool) {
	s := r.site
	socket := s.PHP.Socket
	if socket == "" {
		socket = r.opt.DefaultPHPSocket
	}
	if socket == "" && looksLikePHPServerVersion(s.PHP.Version) {
		// Debian/Ubuntu 上 PHP-FPM 实际 socket 名是 phpX.Y-fpm.sock（无连字符），
		// 不是 php-X.Y-fpm.sock。hardcode 错会让 fastcgi_pass 指向不存在的文件，
		// 根域所有 PHP 请求（首页、/api/*、favicon.ico 经 try_files 落到 index.php）
		// 全 502 Bad Gateway。symlink 形式 php-fpm.sock 也能用但依赖 alternatives 配置。
		socket = fmt.Sprintf("/run/php/php%s-fpm.sock", s.PHP.Version)
	}
	r.w("%sfastcgi_pass unix:%s;", indent, socket)
	r.w("%sfastcgi_index index.php;", indent)
	// SCRIPT_FILENAME 只能出现一次：nginx 会取最后一个值，
	// 输出两条等于白白多写，且容易在排查时造成误判。
	runPath := strings.Trim(s.Root.RunPath, "/")
	if subdir {
		if runPath != "" {
			r.w("%sfastcgi_param SCRIPT_FILENAME $realpath_root/%s$fastcgi_script_name;", indent, runPath)
		} else {
			r.w("%sfastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;", indent)
		}
	} else {
		if runPath != "" {
			r.w("%sfastcgi_param SCRIPT_FILENAME $document_root/%s$fastcgi_script_name;", indent, runPath)
		} else {
			r.w("%sfastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;", indent)
		}
	}
	r.w("%sfastcgi_param PATH_INFO $fastcgi_path_info;", indent)
	r.w("%sinclude fastcgi_params;", indent)
}

func (r *renderer) buildRedirects() {
	for _, rule := range r.site.Redirect.Rules {
		if !rule.Enable || rule.From == "" || rule.To == "" {
			continue
		}
		status := rule.Status
		if status != 301 && status != 302 {
			status = 301
		}
		if strings.HasPrefix(rule.From, "~") {
			// 正则重定向，用 location。
			if !r.claimLocation(rule.From) {
				r.w("    # 跳过重复的重定向来源 %s（nginx 不允许重复 location）", rule.From)
				continue
			}
			r.w("    location %s {", rule.From)
			r.w("        return %d %s;", status, rule.To)
			r.w("    }")
			continue
		}
		// 普通路径：用精确匹配（不补尾斜杠，/old.html 与 /old.html/ 是不同资源）
		from := normalizeExactPath(rule.From)
		if !r.claimLocation(from) {
			r.w("    # 跳过重复的重定向来源 %s（与主 location 或其它规则冲突）", from)
			continue
		}
		r.w("    location %s {", from)
		r.w("        return %d %s;", status, rule.To)
		r.w("    }")
	}
}

// buildRewrites 输出伪静态规则。
// 规则由用户在面板里以原始 rewrite 指令形式填写，这里原样注入 server 块。
// 早期版本 RenderOptions.PathRewrites 定义了却从未被消费，导致伪静态
// 配置静默丢失——界面显示已启用，nginx 里却一行都没有。
func (r *renderer) buildRewrites() {
	rules := strings.TrimSpace(r.opt.PathRewrites)
	if rules == "" {
		return
	}
	r.w("")
	r.w("    # ---- 伪静态规则 ----")
	for _, line := range strings.Split(rules, "\n") {
		if strings.TrimSpace(line) == "" {
			continue
		}
		r.w("    %s", line)
	}
}

// buildRawConf 输出用户自定义配置。
func (r *renderer) buildRawConf() {
	if strings.TrimSpace(r.site.RawConf) == "" {
		return
	}
	r.w("")
	r.w("    # ---- 自定义配置 ----")
	for _, line := range strings.Split(r.site.RawConf, "\n") {
		r.w("    %s", line)
	}
}

// staticExts 规范化静态文件扩展名列表并做正则转义。
func staticExts(raw []string) []string {
	out := make([]string, 0, len(raw))
	for _, e := range raw {
		e = strings.TrimSpace(strings.TrimPrefix(e, "."))
		if e != "" {
			out = append(out, regexp.QuoteMeta(e))
		}
	}
	return out
}

// indexDefaults 返回默认文档列表。
func indexDefaults(c model.IndexConf) []string {
	if len(c.Files) > 0 {
		return c.Files
	}
	return []string{"index.php", "index.html", "index.htm"}
}

// gzipTypes 返回 gzip 类型列表。
